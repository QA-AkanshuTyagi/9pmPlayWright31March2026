//assignment operator: =, +=, -=, *=, /=, %=, **=

//assigning of the value

let x=10;
console.log(x);  // 10
x+=5;
console.log(x);   //15
x-=2;
console.log(x);  //15-2=13
x*=5;
console.log(x);  //13*5=65

x/=5;
console.log(x);  //65/5=13

x%=5;
console.log(x); // 13%5=3


x**=5;
console.log(x); // 3**5=243 (3^5)